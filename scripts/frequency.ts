// Ranks the built-in words by how common they are, for teaching the most useful words first.
// Source: German OpenSubtitles frequencies from FrequencyWords (hermitdave), CC BY-SA 4.0.
// Usage: download de_50k.txt into audio-build/freq/, then
//   npx tsx scripts/frequency.ts > src/content/words/frequency.ts
import { readFileSync } from 'node:fs'
import { BUILT_IN_WORDS } from '../src/content/words'

const ranks = new Map<string, number>()
readFileSync('audio-build/freq/de_50k.txt', 'utf8')
  .split('\n')
  .forEach((line, index) => {
    const [form] = line.split(' ')
    if (form && !ranks.has(form)) ranks.set(form, index + 1)
  })

/** A phrase is about as common as its rarest word, so "ab und zu" isn't ranked as "und". */
function lemmaRank(german: string): number | undefined {
  const words = german.toLowerCase().replace(/^sich /, '').replace(/…/g, '').split(' ').filter(Boolean)
  const found = words.map((word) => ranks.get(word))
  return found.every((rank) => rank !== undefined) ? Math.max(...(found as number[])) : undefined
}

/** The most common of the lemma, the plural and a one-word present form ("geht nach" says nothing about nachgehen). */
function rankOf(german: string, plural?: string, forms?: string): number | undefined {
  const candidates = [lemmaRank(german)]
  if (plural) candidates.push(ranks.get(plural.toLowerCase()))
  const present = forms?.split(',')[0].trim().split(' ') ?? []
  if (present.length === 1) candidates.push(ranks.get(present[0].toLowerCase()))
  const found = candidates.filter((rank): rank is number => rank !== undefined)
  return found.length > 0 ? Math.min(...found) : undefined
}

const entries: [string, number][] = []
for (const word of BUILT_IN_WORDS) {
  const rank = rankOf(word.german, word.plural, word.forms)
  if (rank !== undefined) entries.push([word.id, rank])
}

console.log(`// Generated by scripts/frequency.ts. Do not edit.
// Frequency rank per word id (1 = most common), from German OpenSubtitles counts in
// FrequencyWords by Hermit Dave (https://github.com/hermitdave/FrequencyWords), CC BY-SA 4.0.
export const FREQUENCY_RANK: Record<string, number> = {
${entries.map(([id, rank]) => `  '${id}': ${rank},`).join('\n')}
}`)
